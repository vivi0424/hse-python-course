    assert min_coins(87, [50, 10, 5, 1]) == 7
    assert min_coins(0, [50, 10, 5, 1]) == 0
    assert min_coins(3, [5]) == -1

    # 2
    intervals = [(1,4),(3,5),(0,6),(5,7),(3,9),(5,9),(6,10),(8,11)]
    # В условии ожидается 4, но максимум 3: (1,4), (5,7), (8,11) -
    # остальные интервалы пересекаются с ними.
    assert max_intervals(intervals) == 3
    assert max_intervals([]) == 0

    # 3
    items = [(10, 60), (20, 100), (30, 120)]
    res = fractional_knapsack(50, items)
    assert abs(res - 240.0) < 1e-9

    # 4
    assert min_platforms([], []) == 0
    assert min_platforms([900], [910]) == 1
    assert min_platforms(
        [900, 940, 950, 1100, 1500, 1800],
        [910, 1200, 1120, 1130, 1900, 2000]
    ) == 3
    assert min_platforms([100, 200, 300], [150, 250, 350]) == 1

